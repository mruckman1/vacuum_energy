"""Detector imperfections: loss, thermal bath, dephasing (Layer 2, M2.6).

Spec: ``with_imperfections(V, eta, nbar, dephasing)`` composes
``vacuum.core.channels`` on the *detector* modes of a harvesting protocol;
the field-side temperature enters through
``vacuum.core.thermal_state_cov``.  Everything here is a pure function over
arrays (no hidden state, no input mutation) — Layer 6 JAX-mirror
pre-positioning — and every channel is returned in ``(X, Y)`` form so its
complete positivity is *checkable*, not asserted.

Complete positivity (Holevo-Werner)
-----------------------------------
A Gaussian channel V -> X V X^T + Y is completely positive iff

    Y + (i/2) (Omega - X Omega X^T)  >=  0                            (CP)

as a Hermitian matrix (A. S. Holevo, R. F. Werner, Phys. Rev. A 63, 032312
(2001), Eq. (3.4); A. Serafini, "Quantum Continuous Variables", CRC 2017,
Sec. 5.3), with Omega the block-ordered symplectic form of docs/API.md.
:func:`holevo_werner_matrix` builds the left-hand side and
:func:`is_completely_positive` tests it; the module's channels satisfy it
by construction and the test suite checks every one of them.

The frequency-scaling rule
--------------------------
``vacuum.core.channels`` is written in the dimensionless convention where
the vacuum covariance is I/2.  A detector oscillator of gap Omega_d,
however, lives in H_d = (1/2)(p^2 + Omega_d^2 x^2), whose ground state is
V = diag(1/(2 Omega_d), Omega_d/2) — *not* I/2.  Applying a bare core
channel to such a mode would relax it toward the wrong state.  So every
channel here is conjugated by the (symplectic, diagonal) rescaling

    Sigma_d = diag(sqrt(Omega_d), 1/sqrt(Omega_d))    (x-row, p-row)

which maps the mode to its dimensionless quadratures:

    X' = Sigma^{-1} X Sigma,      Y' = Sigma^{-1} Y Sigma^{-1}.

Because Sigma is real and symplectic, the (CP) matrix transforms by the
congruence M -> Sigma^{-1} M Sigma^{-1}, so CP is preserved exactly — a
theorem this module tests rather than assumes.  With ``gaps=None`` every
Omega_d is 1 and the channels reduce *identically* to the bare
``vacuum.core.channels`` maps.

Consequence worth stating: loss with eta -> 0 and bath occupation
nbar = 1/(e^{Omega_d/T} - 1) drives the detector exactly to
``thermal_state_cov([[Omega_d^2]], T)`` — the detector bath and the field
bath are then the same temperature, described by the same formula.

The circuit-QED dephasing mapping (chosen, documented)
------------------------------------------------------
In circuit QED the dominant detector dephasing is low-frequency flux (or
charge) noise that jitters the detector frequency; for a *qubit* that is
the sigma_z coupling with pure-dephasing rate Gamma_phi, e.g. the
transmission-line contribution Gamma_phi^TL = 2 k_B T phi_0^2
|gamma_{5,11} - gamma_{5,00}|^2 / (hbar^2 Z_0) of N. Janzen, X. Dai,
S. Ren, J. Shi, A. Lupascu, Phys. Rev. Research 5, 033155 (2023), Eq. (15)
(arXiv:2208.05571).

Mapping that onto the *harmonic* (Gaussian) detector of the M2.2 stack
needs care, and the choice is made explicitly here:

1. The literal oscillator transcription of frequency jitter is the
   number-dephasing Lindbladian L = sqrt(2 Gamma_phi) a^dag a.  Its second
   moments do close — <a^dag a> is conserved while <a^2> decays as
   e^{-4 Gamma_phi t} — but the induced map on the covariance,

       V -> (nbar_V + 1/2) I + e^{-4 Gamma_phi t} (V - (nbar_V + 1/2) I),

   depends on the *state* through nbar_V = Tr(V~)/2 - 1/2.  It is
   therefore NOT of the form V -> X V X^T + Y: number dephasing is not a
   Gaussian channel, and it is deliberately not used here.

2. The Gaussian channel that *is* phase-covariant (it commutes with the
   free rotation e^{-i Omega_d t a^dag a}, which is a rigid rotation in the
   rescaled quadratures) is the classical-noise channel generated by
   Hermitian *linear* Lindblad operators — the standard Gaussian
   dephasing/diffusion channel:

       drho/dt = (Gamma_phi/2) ( D[x~] + D[p~] ) rho,
       D[A] rho = 2 A rho A - A^2 rho - rho A^2 = -[A, [A, rho]],

   giving dV~/dt = Gamma_phi I_2, i.e. over a window tau

       X = I,   Y~ = D I_2,   D = Gamma_phi * tau.               (chosen)

   This is exactly ``vacuum.core.channels.thermal_noise`` with
   nbar_added = D, conjugated by the frequency rescaling.  CP is immediate:
   X = I makes (CP) read Y >= 0.

3. The spec's alternative — "``thermal_noise`` on p only" — is the
   single-quadrature version, one Hermitian Lindblad operator
   L = sqrt(2 Gamma_phi) x~ (random momentum kicks; the Caldeira-Leggett /
   position-localization form).  It is offered as ``axis='p'`` (and
   ``axis='x'``), normalized to add the *same* total quadrature variance
   as the isotropic map, Y~ = 2 D e_p e_p^T (equal Tr Y~ = 2 D, hence equal
   added energy), so the two mappings differ only in their anisotropy.

Both are additive-classical-noise (X = I) channels, hence CP for D >= 0,
non-unital in energy — they heat the detector, and the M2.2/protocol
ledgers book that heating as a (negative) dissipation entry automatically.

Rates in, channel parameters out
--------------------------------
:func:`imperfections_from_rates` converts a relaxation rate Gamma_1, a pure
dephasing rate Gamma_phi and a bath temperature T (all in the program's
hbar = k_B = 1 lattice units — ``vacuum.experiments_io`` is the only place
physical units are converted) into (eta, nbar, D) over an interaction
window tau:

    eta = exp(-Gamma_1 tau),   nbar = 1/(e^{Omega_d/T} - 1),
    D   = Gamma_phi (1 - eta) / Gamma_1   ( -> Gamma_phi tau as Gamma_1 -> 0),

the last being the *exact* integral of the combined Lindbladian rather
than a product of separately integrated pieces — see
:func:`imperfection_channel` for why that distinction sets the order of
the Trotter splitting.

:func:`circuit_qed_noise` does the same starting from a validated
``experiments/`` parameter file, so a sweep row inherits its provenance.

Conventions per docs/API.md: hbar = k_B = 1, V_vac = I/2 (dimensionless
quadratures), nu >= 1/2, block ordering R = (x_1..x_N, p_1..p_N).
"""

