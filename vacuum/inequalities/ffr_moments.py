"""Fewster-Ford-Roman (2012) moment method, transcribed and run on our kernel.

C. J. Fewster, L. H. Ford and T. A. Roman, "Probability distributions for
quantum stress tensors in four dimensions", Phys. Rev. D 85, 125038 (2012)
[arXiv:1204.3570], compute the vacuum moments of the Lorentzian-smeared Wick
squares :phi^2: (p = 1) and :phidot^2: (p = 3) of the 4d massless scalar,
and estimate the lower edge of the probability distribution -- which, by their
Sec. II argument, is the optimal quantum-inequality bound x0 -- by a Stieltjes
moment test. This module reproduces every step of that pipeline so that it can
be run on demand next to our direct minimization of the same operator.

Their conventions (transcribed)
-------------------------------
* Sampling function f(t) = tau / (pi (t^2 + tau^2)), Eq. (9); dimensionless
  moments a_n = (4 pi tau)^{2n} mu_n for phi^2 (Eq. 19) and
  a_n = (4 pi tau^2)^{2n} mu_n for phidot^2 (Eq. 20); mu_n = <T^n>_vac with
  T = int f :phi^2: dt, Eq. (12).
* Appendix A (Fourier-space rules). Two-point function
  <phi(t) phi(t')> = (4 pi^2)^{-1} int_0^inf dw w^p e^{-i w (t - t' - i eps)}
  (A1); a connected n-vertex graph is a permutation with "runs"; for the
  Lorentzian, fhat(w) = e^{-|w| tau} makes every double-source / double-target
  vertex factorize, so each graph is a product over its runs of the chain
  integrals (A3)

      K_n^{(r)} = (2^r/r!) int_{R+^n} dk_1..dk_n k_1^{p+r} (k_2..k_n)^p
                  e^{-k_1} e^{-sum_i |k_{i+1} - k_i|} e^{-k_n},

  evaluated exactly by the recurrence (A6)
      K_n^{(r)} = (p!/2^{p+1}) C(p+r, p) sum_{r'=0}^{p+r+1} K_{n-1}^{(r')},
      K_1^{(r)} = 2^{-(p+1)} p! C(p+r, p),
  and the sum over graphs is generated by the run-structure polynomials (A8)
      script-K_n = sum_i K_{i+1} d script-K_{n-1}/dK_i
                   + sum_{i,j} K_1 K_i K_j d script-K_{n-1}/dK_{i+j},
      script-K_2 = K_1^2/2,
  with the connected moments C_2 = 32 K_1^2, C_n = 8^n script-K_n (n >= 3)
  [their (A9)-(A14) give C_2..C_7 explicitly] and the full moments from
  M = e^W (Eqs. 21-23).
* Sec. IV (Eqs. 58-64). For a distribution supported on [-x0, inf),
  M(N, y)_{mn} = a_{m+n+1} + y a_{m+n} (0 <= m, n < N) is positive
  semidefinite for y >= x0; y_N = largest root of det M(N, y) = 0 is
  increasing in N with y_inf = lim y_N <= x0 (Eq. 64). They tabulate y_N for
  N <= 32 (Table II, 40-digit Maple) and fit y_N = a + b N^{-1/2} + c/N
  + d N^{-3/2} on 21 <= N <= 33 (Eq. 68), giving y_inf(phidot^2) = 0.02361
  +- 1e-5, which their Eq. (69) offers as the estimate of the optimal bound;
  the caveat at the end of Sec. IV: for a Hamburger-indeterminate moment
  problem y_inf = x_F < x0 (the Friedrichs solution's edge).

What is ours here
-----------------
* The run-structure recursion (A8) is a first-order derivation D on the
  polynomial ring in K_1, K_2, ...; hence script-K_n = D^{n-2} (K_1^2/2)
  = (d/ds)^{n-2} [K_1(s)^2/2]|_{s=0} along the flow
      dK_k/ds = K_{k+1} + K_1 sum_{i+j=k} K_i K_j .
  Evaluated as truncated power series in exact rationals this gives all
  connected moments to any order in seconds, without enumerating the
  ~10^6 run structures at n = 65 (their "2811 terms at n = 30"); it
  reproduces (A9)-(A14) symbolically (checked in the tests).
* On our own kernel (`vacuum.inequalities.qei`, Ford-Roman weight
  `sqrt_lorentzian_f`) the anomalous block is rank one,
  B(w, w') = u(w) u(w')/(2 pi^2), u = w^{3/2} e^{-w tau} sqrt(pi), so the
  necklace traces collapse to the same chain integrals:
      K_n^{(0)} = (2 pi)^{n-1} u^T A^{n-1} u   (tau = 1, p = 3),
  which :func:`kernel_chain_integrals` evaluates by Nystrom quadrature and
  compares with the exact recurrence -- the identification of our operator
  with theirs, normalization included (a_2 = 9/2 is exact by hand:
  (16 pi)^2 (1/2) Tr B^2 = 256 pi^2 (3/8)^2 / (8 pi^2) = 9/2).
* The Stieltjes test: the roots of det(a_{m+n+1} + y a_{m+n}) = 0 are minus
  the zeros of the N-th orthogonal polynomial of the moment sequence (the
  Gauss nodes), so y_N = -(smallest Gauss node); the recurrence coefficients
  are computed exactly (Chebyshev algorithm on the rational moments) and the
  Jacobi-matrix eigenvalues in mpmath -- the well-conditioned form of their
  40-digit determinant computation.
* Carleman/growth diagnostics (Appendix B: a_n ~ power x (3n-4)!) and a
  "blindness" experiment: a point mass added at -x* changes y_N by an amount
  the test cannot resolve, which is the mechanism behind y_inf < x0.

All functions are pure; exact arithmetic uses `fractions.Fraction`,
high-precision linear algebra uses mpmath at the caller's dps.
"""

