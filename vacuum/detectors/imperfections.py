# Temperatures: the field side (thermal_state_cov) and the detector bath
# --------------------------------------------------------------------------


def bath_occupation(omega, T):
    """Bose occupation nbar = 1/(e^{omega/T} - 1) in lattice units.

    Thin, documented wrapper on ``vacuum.experiments_io.bose_occupation``
    (hbar = k_B = 1: only the ratio omega/T enters).  T = 0 gives 0.
    Accepts an array of frequencies.
    """
    w = np.asarray(omega, dtype=float)
    if w.ndim == 0:
        return bose_occupation(float(w), float(T))
    return np.array([bose_occupation(float(x), float(T)) for x in w])


def field_thermal_state(K, T):
    """Field covariance at temperature T (spec M2.6: via ``thermal_state_cov``).

    The field side of "imperfections" is temperature, and it enters exactly
    one way: ``vacuum.core.thermal_state_cov(K, T)``, whose T = 0 branch
    reproduces ``ground_state_cov(K)`` identically.  This wrapper exists so
    that a harvesting protocol never hand-rolls a thermal covariance;
    it forwards unchanged.
    """
    T = float(T)
    if T < 0.0:
        raise ValueError(f"temperature must be >= 0, got {T}")
    if T == 0.0:
        return ground_state_cov(K)
    return thermal_state_cov(K, T)


def field_bath_occupations(K, T):
    """Per-normal-mode occupations of the thermal field state.

    With K = U diag(omega^2) U^T, returns (omega, nbar) with
    nbar_k = 1/(e^{omega_k/T} - 1) — the occupations whose
    sum_k omega_k (nbar_k + 1/2) is ``mean_energy(thermal_state_cov(K, T), K)``.
    """
    K = np.asarray(K, dtype=float)
    w2 = np.linalg.eigvalsh(0.5 * (K + K.T))
    if np.min(w2) <= 0.0:
        raise ValueError(
            f"K must be positive definite for a thermal state: min eig {np.min(w2):.3e}"
        )
    omega = np.sqrt(w2)
    return omega, bath_occupation(omega, T)


