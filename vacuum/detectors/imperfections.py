# --------------------------------------------------------------------------
# Complete positivity: the Holevo-Werner condition, made checkable
# --------------------------------------------------------------------------


def holevo_werner_matrix(X, Y):
    """Hermitian matrix of the CP condition: Y + (i/2)(Omega - X Omega X^T).

    Holevo-Werner, Phys. Rev. A 63, 032312 (2001), Eq. (3.4): a Gaussian
    map V -> X V X^T + Y is completely positive iff this matrix is positive
    semidefinite (Omega in the block ordering of docs/API.md).
    """
    X = np.asarray(X, dtype=float)
    Y = np.asarray(Y, dtype=float)
    if X.shape != Y.shape or X.ndim != 2 or X.shape[0] != X.shape[1]:
        raise ValueError(f"X, Y must be equal square matrices, got {X.shape}, {Y.shape}")
    N = X.shape[0] // 2
    if X.shape[0] != 2 * N:
        raise ValueError(f"X, Y must have even dimension, got {X.shape[0]}")
    Om = symplectic_form(N)
    return Y.astype(complex) + 0.5j * (Om - X @ Om @ X.T)


def holevo_werner_margin(X, Y):
    """Smallest eigenvalue of :func:`holevo_werner_matrix` (>= 0 iff CP).

    The *margin* is reported (not a bool) so failures print a number, per
    the repo's testing convention.
    """
    return float(np.min(np.linalg.eigvalsh(holevo_werner_matrix(X, Y))))


def is_completely_positive(X, Y, tol=1e-12):
    """True iff the Holevo-Werner margin is >= -tol (roundoff-tolerant)."""
    return holevo_werner_margin(X, Y) >= -abs(float(tol))


