def _mode_list(N, modes):
    m = tuple(int(k) for k in modes)
    if not m:
        raise ValueError("need at least one mode index")
    if len(set(m)) != len(m):
        raise ValueError(f"repeated mode index in {m}")
    for k in m:
        if not 0 <= k < N:
            raise IndexError(f"mode index {k} out of range for N={N}")
    return m


def _gap_array(modes, gaps):
    """Per-mode gaps, broadcast from a scalar; None -> all ones."""
    n = len(modes)
    if gaps is None:
        return np.ones(n)
    g = np.asarray(gaps, dtype=float)
    if g.ndim == 0:
        g = np.full(n, float(g))
    if g.shape != (n,):
        raise ValueError(f"gaps shape {g.shape} != ({n},) (one gap per mode)")
    if np.any(g <= 0.0):
        raise ValueError(f"detector gaps must be > 0, got {g}")
    return g


def mode_scaling(N, modes, gaps):
    """Diagonal of the symplectic rescaling Sigma to dimensionless quadratures.

    Returns the length-2N diagonal of Sigma: sqrt(Omega_d) on the x row and
    1/sqrt(Omega_d) on the p row of each listed mode, 1 elsewhere.  Sigma is
    symplectic (each mode block has determinant 1 and is diagonal), so
    conjugating a channel by it preserves complete positivity exactly (see
    the module docstring).  ``gaps=None`` returns all ones.
    """
    N = int(N)
    m = _mode_list(N, modes)
    g = _gap_array(m, gaps)
    s = np.ones(2 * N)
    for k, gap in zip(m, g):
        s[k] = math.sqrt(gap)
        s[N + k] = 1.0 / math.sqrt(gap)
    return s


def scale_channel(X, Y, s):
    """Conjugate a channel by the diagonal rescaling with diagonal `s`.

    X' = Sigma^{-1} X Sigma, Y' = Sigma^{-1} Y Sigma^{-1} with
    Sigma = diag(s) — the channel written in the original (unscaled)
    quadratures.  Pure function; inputs are not mutated.
    """
    X = np.asarray(X, dtype=float)
    Y = np.asarray(Y, dtype=float)
    s = np.asarray(s, dtype=float)
    inv = 1.0 / s
    Xp = (inv[:, None] * X) * s[None, :]
    Yp = (inv[:, None] * Y) * inv[None, :]
    return Xp, Yp


