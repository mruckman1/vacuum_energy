def imperfection_channel(modes, kappa=0.0, nbar=0.0, gamma_phi=0.0,
                         axis="isotropic", gaps=None):
    """Rate-based channel callable ``(V, t, dt) -> V`` for ``protocol_evolve``.

    ``vacuum.detectors.protocol_evolve`` interleaves channels in a Strang
    splitting and hands each one the substep duration, so the channel must
    own its dt-scaling for the Trotter limit to converge (spec M2.2).  This
    factory returns the EXACT propagator of the combined Lindbladian over a
    duration dt — damping at rate `kappa` toward a bath of occupation
    `nbar`, plus dephasing diffusion at rate `gamma_phi` — not a product of
    separately integrated pieces.  In the rescaled quadratures the combined
    generator is linear,

        dV~/dt = -kappa (V~ - (nbar + 1/2) I) + gamma_phi * G,
        G = I_2 (isotropic) or 2 e_p e_p^T (axis='p'), and its solution is

        eta = exp(-kappa dt),    D = gamma_phi (1 - eta) / kappa,

    which is exactly :func:`with_imperfections` at those arguments and
    reduces to D = gamma_phi dt as kappa -> 0 (computed stably with expm1).

    This matters for the splitting order: a semigroup composes,
    C_{dt/2} o C_{dt/2} = C_{dt}, so the two Strang half-applications join
    with no error and the interleaved evolution stays *second* order in dt,
    set by the Magnus stepper alone.  Integrating loss and dephasing
    separately and composing them would leave an O(dt) commutator error and
    drop the dt-halving gate to first order.

    The returned closure is pure: it captures only frozen parameters and
    ignores the absolute time t (a time-dependent noise schedule would
    take t).
    """
    m = tuple(int(k) for k in modes)
    kappa = float(kappa)
    gamma_phi = float(gamma_phi)
    if kappa < 0.0:
        raise ValueError(f"kappa must be >= 0, got {kappa}")
    if gamma_phi < 0.0:
        raise ValueError(f"gamma_phi must be >= 0, got {gamma_phi}")
    if axis not in DEPHASING_AXES:
        raise ValueError(f"axis must be one of {DEPHASING_AXES}, got {axis!r}")
    gaps_t = None if gaps is None else tuple(np.atleast_1d(np.asarray(gaps, float)))

    def channel(V, t, dt):
        dt = float(dt)
        eta = math.exp(-kappa * dt)
        # (1 - e^{-kappa dt}) / kappa, stable in both limits (-> dt at kappa=0)
        window = dt if kappa == 0.0 else -math.expm1(-kappa * dt) / kappa
        return with_imperfections(
            V,
            m,
            eta=eta,
            nbar=nbar,
            dephasing=gamma_phi * window,
            axis=axis,
            gaps=gaps_t,
        )

    return channel


def imperfection_step(modes, eta=1.0, nbar=0.0, dephasing=0.0, axis="isotropic",
                      gaps=None, label="imperfections"):
    """A :class:`vacuum.protocol.ChannelStep` applying :func:`with_imperfections`.

    The instantaneous (already-integrated) form, for protocols assembled as
    a step list and run through :func:`vacuum.protocol.run_protocol`: the
    runner books the channel's mean-energy change as a ledger ``dissipate``
    entry, so the books close automatically.
    """
    from vacuum.protocol import ChannelStep  # local import: keeps this module light

    return ChannelStep(
        channel=with_imperfections,
        args=(tuple(int(k) for k in modes),),
        kwargs={
            "eta": float(eta),
            "nbar": float(nbar),
            "dephasing": float(dephasing),
            "axis": axis,
            "gaps": gaps,
        },
        label=label,
    )


