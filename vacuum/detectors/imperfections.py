def imperfections_from_rates(gaps, tau, T=0.0, Gamma_1=0.0, Gamma_phi=0.0,
                             axis="isotropic", provenance=None):
    """Map physical rates over a window tau to an :class:`Imperfections`.

    All arguments are in the program's lattice units (hbar = k_B = 1);
    ``vacuum.experiments_io`` is the only place SI values are converted.

        eta  = exp(-Gamma_1 tau)                 (energy relaxation)
        nbar = 1/(e^{Omega_d/T} - 1)             (bath occupation at the gap)
        D    = Gamma_phi (1 - eta) / Gamma_1     (integrated pure dephasing)

    The dephasing integral is the exact solution of the *combined*
    Lindbladian (:func:`imperfection_channel`), not Gamma_phi * tau, which
    it reduces to as Gamma_1 -> 0; the two differ at order Gamma_1 tau and
    the exact form is what makes the map a semigroup.  Consequently
    ``imperfections_from_rates(gaps, tau, T, G1, Gphi).apply(V, modes)``
    equals ``imperfection_channel(modes, G1, nbar, Gphi, gaps=gaps)(V, t,
    tau)`` identically.

    A single bath occupation is used, evaluated at the *mean* detector gap
    when the gaps differ, and the per-detector gaps are kept for the
    frequency rescaling; harvesting protocols use equal-gap detector pairs,
    and unequal gaps with a shared bath would need one channel per detector
    (call :func:`with_imperfections` per mode in that case).
    """
    g = np.atleast_1d(np.asarray(gaps, dtype=float))
    if np.any(g <= 0.0):
        raise ValueError(f"detector gaps must be > 0, got {g}")
    tau = float(tau)
    if tau < 0.0:
        raise ValueError(f"tau must be >= 0, got {tau}")
    Gamma_1 = float(Gamma_1)
    Gamma_phi = float(Gamma_phi)
    if Gamma_1 < 0.0 or Gamma_phi < 0.0:
        raise ValueError(
            f"rates must be >= 0, got Gamma_1={Gamma_1}, Gamma_phi={Gamma_phi}"
        )
    eta = math.exp(-Gamma_1 * tau)
    window = tau if Gamma_1 == 0.0 else -math.expm1(-Gamma_1 * tau) / Gamma_1
    return Imperfections(
        eta=eta,
        nbar=bath_occupation(float(np.mean(g)), T),
        dephasing=Gamma_phi * window,
        axis=axis,
        gaps=tuple(float(x) for x in g),
        tau=tau,
        provenance=provenance,
    )


#: Default quantity names read by :func:`circuit_qed_noise` from an
#: ``experiments/circuit_qed_harvesting/`` file.  They are the names used by
#: the files this milestone ships; pass explicit keys for other schemas.
CIRCUIT_QED_KEYS = {
    "gap": "qubit_gap_frequency",
    "relaxation": "relaxation_rate_gamma1_max",
    "dephasing": "pure_dephasing_rate_max",
    "temperature": "transmission_line_temperature",
}


def circuit_qed_noise(experiment, omega_ref, tau, *, keys=None, axis="isotropic",
                      gap=None, root=None):
    """Build an :class:`Imperfections` from a validated parameter file.

    Parameters
    ----------
    experiment : str or vacuum.experiments_io.Experiment
        A name under ``experiments/`` (loaded through
        :func:`vacuum.experiments_io.load_experiment`, which enforces the
        provenance rules and refuses incomplete files) or an already-loaded
        record.
    omega_ref : float
        Reference angular frequency (rad/s) fixing the lattice energy unit;
        the file's SI values are converted in ``vacuum.experiments_io`` and
        nowhere else.
    tau : float
        Interaction window in lattice time units (t * omega_ref).
    keys : mapping, optional
        Overrides for :data:`CIRCUIT_QED_KEYS`.
    gap : float, optional
        Detector gap in lattice units, overriding the file's gap quantity
        (harvesting sweeps scan the gap; the file fixes the device).
    root : path-like, optional
        Alternate experiments root.

    Notes
    -----
    Rates published as ordinary frequencies (MHz, GHz) are converted by the
    loader's energy rule, ``value * 2 pi / omega_ref`` — i.e. they are read
    as angular rates.  Papers are not always explicit about the 2 pi in a
    quoted "Gamma_1 = 8.7 MHz"; the convention used here is stated in the
    parameter files' notes, and a factor-2 pi ambiguity in a published rate
    is a provenance question for the source, never something to silently
    absorb in code.
    """
    exp = (
        experiment
        if hasattr(experiment, "quantities")
        else load_experiment(experiment, root=root)
    )
    kk = dict(CIRCUIT_QED_KEYS)
    if keys:
        kk.update(keys)
    lat = exp.lattice(float(omega_ref))
    missing = [v for k, v in kk.items() if k != "gap" and v not in lat]
    if missing:
        raise KeyError(
            f"experiment {exp.name!r} has no lattice-convertible quantity for "
            f"{missing} (available: {sorted(lat)})"
        )
    if gap is None:
        if kk["gap"] not in lat:
            raise KeyError(
                f"experiment {exp.name!r} has no gap quantity {kk['gap']!r}; "
                f"pass gap=... explicitly"
            )
        gap = lat[kk["gap"]]
    gap_val = float(np.mean(np.atleast_1d(np.asarray(gap, dtype=float))))
    return imperfections_from_rates(
        gaps=gap_val,
        tau=float(tau),
        T=float(np.max(np.atleast_1d(np.asarray(lat[kk["temperature"]], float)))),
        Gamma_1=float(np.max(np.atleast_1d(np.asarray(lat[kk["relaxation"]], float)))),
        Gamma_phi=float(
            np.max(np.atleast_1d(np.asarray(lat[kk["dephasing"]], float)))
        ),
        axis=axis,
        provenance=f"{exp.name} (source: {exp.source[:80]}...)",
    )
