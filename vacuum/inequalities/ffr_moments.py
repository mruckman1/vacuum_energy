def chain_integrals_exact(p, n_max):
    """K_n^{(0)}, n = 1..n_max, exactly, by FFR (A6); returns a list with K[0] = None."""
    p = int(p)
    n_max = int(n_max)
    pref = Fraction(factorial(p), 2 ** (p + 1))
    rmax = (p + 2) * n_max + 2
    prev = {r: pref * comb(p + r, p) for r in range(rmax + 1)}
    K = [None, prev[0]]
    for n in range(2, n_max + 1):
        cur = {}
        for r in range(rmax - (p + 2) * (n - 1) + 1):
            cur[r] = pref * comb(p + r, p) * sum(prev[rp] for rp in range(p + r + 2))
        K.append(cur[0])
        prev = cur
    return K


def run_structure_cumulants(K, n_max):
    """Connected dimensionless moments C_2..C_n_max from the chain integrals.

    script-K_n = (d/ds)^{n-2} [K_1(s)^2 / 2] at s = 0 along the flow
    dK_k/ds = K_{k+1} + K_1 sum_{i+j=k} K_i K_j (the flow of FFR's derivation
    (A8)); C_2 = 32 K_1^2, C_n = 8^n script-K_n. `K` may hold Fractions
    (exact) or floats; missing K_k beyond the list are taken as zero, which
    is harmless because K_k first enters script-K_n at n = k + 1.
    """
    n_max = int(n_max)
    M = n_max - 2
    zero = K[1] * 0
    kmax = M + 2
    ser = {k: [zero] * (M + 1) for k in range(1, kmax + 2)}
    for k in range(1, kmax + 2):
        ser[k][0] = K[k] if k < len(K) else zero
    # T_k[m] = coefficient of s^m in sum_{i+j=k} K_i K_j ;  conv_k[m] = coefficient of s^m in K_1 * T_k
    T = {k: [zero] * (M + 1) for k in range(1, kmax + 1)}
    for m in range(M):
        for k in range(1, kmax + 1):
            t = zero
            for i in range(1, k):
                si, sj = ser[i], ser[k - i]
                for a in range(m + 1):
                    t += si[a] * sj[m - a]
            T[k][m] = t
            conv = zero
            for b in range(m + 1):
                conv += ser[1][b] * T[k][m - b]
            rhs = ser[k + 1][m] if (k + 1) in ser else zero
            ser[k][m + 1] = (rhs + conv) / (m + 1)
    k1 = ser[1]
    h = [zero] * (M + 1)
    for a in range(M + 1):
        for b in range(M + 1 - a):
            h[a + b] += k1[a] * k1[b] / 2
    C = [zero] * (n_max + 1)
    C[2] = 32 * K[1] ** 2
    for n in range(3, n_max + 1):
        C[n] = (8 ** n) * h[n - 2] * factorial(n - 2)
    return C


def moments_from_cumulants(C, n_max):
    """a_n from connected moments C_k (a_0 = 1): a_n = sum_k C(n-1, k-1) C_k a_{n-k}."""
    one = C[2] / C[2] if C[2] != 0 else 1
    a = [one] + [C[2] * 0] * n_max
    for n in range(1, n_max + 1):
        a[n] = sum(comb(n - 1, k - 1) * C[k] * a[n - k] for k in range(1, n + 1))
    return a


def ffr_moment_sequence(p=3, n_max=65):
    """FFR's dimensionless vacuum moments a_0..a_n_max, exact rationals, by their Appendix A."""
    K = chain_integrals_exact(p, n_max)
    C = run_structure_cumulants(K, n_max)
    return moments_from_cumulants(C, n_max), C, K


def _to_mpf(x, mp):
    if isinstance(x, Fraction):
        return mp.mpf(x.numerator) / x.denominator
    return mp.mpf(x)


def jacobi_recurrence(a, N):
    """Three-term recurrence coefficients (alpha_k, beta_k), k < N, of the
    monic orthogonal polynomials of the moment sequence a_0..a_{2N-1}, by the
    Chebyshev algorithm (Gautschi, Orthogonal Polynomials, Sec. 2.1.7) in the
    arithmetic of `a` (exact for Fractions). beta_k > 0 for all k < N iff the
    Hankel matrix (a_{m+n})_{m,n<N} is positive definite."""
    N = int(N)
    zero = a[0] * 0
    m = list(a[:2 * N])
    alpha = [m[1] / m[0]]
    beta = [m[0]]
    sig_prev = [zero] * (2 * N)            # sigma_{-1, l}
    sig = list(m)                          # sigma_{0, l}
    for k in range(1, N):
        sig_new = [zero] * (2 * N)
        for l in range(k, 2 * N - k):
            sig_new[l] = sig[l + 1] - alpha[k - 1] * sig[l] - beta[k - 1] * sig_prev[l]
        alpha.append(sig_new[k + 1] / sig_new[k] - sig[k] / sig[k - 1])
        beta.append(sig_new[k] / sig[k - 1])
        sig_prev, sig = sig, sig_new
    return alpha, beta


def stieltjes_edge(a, N, dps=60):
    """y_N of FFR Eq. (63): the largest root of det(a_{m+n+1} + y a_{m+n}) = 0.

    Those roots are minus the zeros of the N-th orthogonal polynomial of the
    moment sequence (the N-point Gauss nodes), so y_N = -(smallest Gauss
    node): the recurrence coefficients are obtained EXACTLY by the Chebyshev
    algorithm on the rational moments and the nodes as the eigenvalues of the
    symmetric tridiagonal Jacobi matrix in mpmath at `dps` -- the
    well-conditioned form of the same computation (a Cholesky of the Hankel
    matrix itself, whose entries span 10^370 at N = 32, is not)."""
    import mpmath as mp

    N = int(N)
    alpha, beta = jacobi_recurrence(a, N)
    with mp.workdps(int(dps)):
        J = mp.matrix(N, N)
        for k in range(N):
            J[k, k] = _to_mpf(alpha[k], mp)
            if k + 1 < N:
                b = _to_mpf(beta[k + 1], mp)
                if b <= 0:
                    raise ValueError(f"beta_{k + 1} = {b} <= 0: not a positive Hankel matrix at N={N}")
                J[k, k + 1] = J[k + 1, k] = mp.sqrt(b)
        ev = mp.eigsy(J, eigvals_only=True)
        return float(-min(ev))


def stieltjes_sequence(a, N_max=32, N_min=2, dps=60):
    """{N: y_N} for N_min <= N <= N_max (needs a up to a_{2 N_max - 1})."""
    return {N: stieltjes_edge(a, N, dps=dps) for N in range(int(N_min), int(N_max) + 1)}


def ffr_fit_y_inf(yN, N_lo=21, N_hi=33):
    """FFR Eq. (68): least squares y_N = a + b N^{-1/2} + c N^{-1} + d N^{-3/2} on N_lo..N_hi."""
    Ns = np.array([N for N in sorted(yN) if N_lo <= N <= N_hi], dtype=float)
    ys = np.array([yN[int(N)] for N in Ns])
    X = np.vstack([np.ones_like(Ns), Ns**-0.5, 1.0 / Ns, Ns**-1.5]).T
    coef, *_ = np.linalg.lstsq(X, ys, rcond=None)
    res = ys - X @ coef
    return {"y_inf": float(coef[0]), "b": float(coef[1]), "c": float(coef[2]), "d": float(coef[3]),
            "max_resid": float(np.max(np.abs(res))), "N_range": [int(Ns[0]), int(Ns[-1])]}


def carleman_diagnostics(a, p=3, shift=1):
    """Growth and Carleman partial sums of a moment sequence.

    Growth: log a_n - log Gamma(3n - 3) for p = 3 (FFR Appendix B: a_n grows
    as a power times (3n - 4)!), whose increments give the geometric factor.
    Carleman: the Hamburger criterion sum_n a_{2n}^{-1/(2n)} = inf and the
    Stieltjes criterion sum_n b_n^{-1/(2n)} = inf on the moments b_n of the
    shifted variable x + shift (support in [0, inf) needs shift >= x0; a_1 = 0
    makes the unshifted Stieltjes sum degenerate) are SUFFICIENT for
    determinacy; for a_n ~ (3n)! both series converge like sum n^{-3/2}, so
    the criteria are inconclusive -- FFR's Sec. I statement -- while a
    density with the Appendix-B tail exp(-c x^{1/3}) is Krein-indeterminate
    (their Sec. VIII remark on Stieltjes' (3n+2)! example)."""
    import mpmath as mp

    n_max = len(a) - 1
    A = [_to_mpf(x, mp) for x in a]
    lg = [0.0] + [float(mp.log(A[n])) for n in range(1, n_max + 1)]
    growth = ({n: lg[n] - math.lgamma(3 * n - 3) for n in range(4, n_max + 1)} if p == 3 else
              {n: lg[n] - math.lgamma(n + 1) for n in range(4, n_max + 1)})
    ham_terms = [math.exp(-lg[2 * n] / (2 * n)) for n in range(1, n_max // 2 + 1)]
    # shifted moments b_n = sum_k C(n,k) shift^{n-k} a_k
    sh = mp.mpf(shift)
    b = [sum(mp.binomial(n, k) * sh ** (n - k) * A[k] for k in range(n + 1)) for n in range(n_max + 1)]
    sti_terms = [float(mp.exp(-mp.log(b[n]) / (2 * n))) for n in range(1, n_max + 1)]
    ns = np.arange(10, n_max + 1)
    return {"log_a_over_gamma": growth,
            "geometric_factor_per_n": float(math.exp(growth[n_max] - growth[n_max - 1])) if p == 3 else None,
            "hamburger_partial_sum": float(np.sum(ham_terms)), "hamburger_last_terms": ham_terms[-3:],
            "hamburger_term_decay_exponent": float(-np.polyfit(np.log(np.arange(5, n_max // 2 + 1)),
                                                               np.log(ham_terms[4:]), 1)[0]),
            "stieltjes_shift": float(shift), "stieltjes_partial_sum": float(np.sum(sti_terms)),
            "stieltjes_last_terms": sti_terms[-3:],
            "stieltjes_term_decay_exponent": float(-np.polyfit(np.log(ns), np.log(sti_terms[9:]), 1)[0]),
            "verdict": "inconclusive (both Carleman series converge; (3n)!-class growth is the Krein-indeterminate class)"}


def ffr_identity_A4(q, kappa, dps=30):
    """FFR (A4), the elementary identity that turns OUR kernel's chain into
    THEIR recurrence: int_0^inf dk k^q e^{-k} e^{-|k - kappa|}
    = q! e^{-kappa} 2^{-(q+1)} sum_{r=0}^{q+1} (2 kappa)^r / r!. Returns
    (direct mpmath quadrature with the cusp split at k = kappa, closed form,
    relative deviation)."""
    import mpmath as mp

    with mp.workdps(int(dps)):
        q = int(q)
        kap = mp.mpf(kappa)
        direct = (mp.quad(lambda k: k**q * mp.exp(-k) * mp.exp(-(kap - k)), [0, kap])
                  + mp.quad(lambda k: k**q * mp.exp(-k) * mp.exp(-(k - kap)), [kap, mp.inf]))
        closed = mp.factorial(q) * mp.exp(-kap) / 2 ** (q + 1) * mp.fsum((2 * kap) ** r / mp.factorial(r)
                                                                          for r in range(q + 2))
        return float(direct), float(closed), float(abs(direct / closed - 1))


def kernel_chain_integrals(f, p=3, n_max=16, grids=((1500, 60.0), (3000, 60.0), (6000, 60.0))):
    """K_n^{(0)} from OUR operator -- through the same code path the solver
    uses -- against FFR's exact recurrence.

    The kernels are built by :func:`vacuum.inequalities.qei._worldline_kernels`
    from :func:`vacuum.inequalities.qei.fhat_of` (exactly what
    `worldline_momentum_minimize` assembles, and the same transform and
    (ww')^{p/2} weighting `box_wavepacket_state` integrates over its boxes):
    A_wk = (ww')^{p/2} Fhat(w - w'), B_wk = (ww')^{p/2} Fhat(w + w') on a
    uniform Gauss-Legendre grid. For the Ford-Roman weight Fhat = pi e^{-|nu|}
    (tau = 1) the anomalous block is rank one, B_wk = pi v v^T with
    v = w^{p/2} e^{-w} (grid-weighted), which is verified here (v is read off
    the diagonal and the residual |B_wk - pi v v^T| reported), and the
    necklace traces reduce to FFR's chain integral (A3) at r = 0:
    K_n = v^T A'^{n-1} v = pi^{-(n-1)} v^T A_wk^{n-1} v. The cusp of the
    transform limits a uniform Nystrom rule to O(h^2), so three grids of equal
    omega_max are Richardson-extrapolated in h^2. Returns per-grid values,
    the extrapolation, the exact values, the worst deviations and the
    rank-one residual. `f` must carry the Ford-Roman weight (tau = 1)."""
    from .qei import _worldline_kernels, fhat_of, momentum_grid

    Kex = chain_integrals_exact(p, n_max)
    fhat = fhat_of(f)
    per_grid = []
    rank_one_resid = 0.0
    for n_modes, om in grids:
        omg, wom = momentum_grid(om, n_modes, power=1)
        A_wk, B_wk = _worldline_kernels(omg, wom, fhat, p)
        A_wk = np.asarray(A_wk).real
        B_wk = np.asarray(B_wk).real
        v = np.sqrt(np.clip(np.diag(B_wk), 0.0, None) / math.pi)
        rank_one_resid = max(rank_one_resid,
                             float(np.max(np.abs(B_wk - math.pi * np.outer(v, v))) / np.max(np.abs(B_wk))))
        vals, x = [], v.copy()
        for n in range(1, n_max + 1):
            vals.append(float(v @ x) / math.pi ** (n - 1))
            if n < n_max:
                x = A_wk @ x
        del A_wk, B_wk
        per_grid.append({"n_modes": int(n_modes), "omega_max": float(om), "h": float(om / n_modes), "K": vals})
    hs = np.array([g["h"] for g in per_grid])
    out = []
    for n in range(1, n_max + 1):
        ks = np.array([gr["K"][n - 1] for gr in per_grid])
        ex = float(Kex[n])
        X = np.vstack([np.ones(len(hs)), hs ** 2]).T
        c2, *_ = np.linalg.lstsq(X, ks, rcond=None)
        devs = np.abs(ks - ex) / abs(ex)
        monotone = bool(np.all((np.diff(devs) < 0) | (devs[1:] < 1e-11))) if len(ks) > 1 else True
        out.append({"n": n, "exact": ex, "nystrom": ks.tolist(), "richardson_h2": float(c2[0]),
                    "rel_dev_finest": float(ks[-1] / ex - 1), "rel_dev_richardson": float(c2[0] / ex - 1),
                    "converging_monotonically": monotone})
    return {"p": int(p), "per_grid": per_grid, "chain": out, "rank_one_residual": rank_one_resid,
            "code_path": "qei._worldline_kernels(momentum_grid(..), fhat_of(f), p)",
            "worst_rel_dev_finest": max(abs(o["rel_dev_finest"]) for o in out),
            "worst_rel_dev_richardson": max(abs(o["rel_dev_richardson"]) for o in out),
            "all_monotone": all(o["converging_monotonically"] for o in out)}


def point_mass_perturbation(a, x_star, weight):
    """Moments of the mixture (1 - weight) P + weight delta(x + x_star): a_n -> (1-w) a_n + w (-x*)^n."""
    w = Fraction(weight) if not isinstance(weight, Fraction) else weight
    xs = Fraction(x_star) if not isinstance(x_star, Fraction) else x_star
    return [(1 - w) * a[n] + w * (-xs) ** n for n in range(len(a))]
