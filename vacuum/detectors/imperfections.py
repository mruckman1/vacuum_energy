def loss_channel_XY(N, modes, eta, nbar=0.0, gaps=None):
    """(X, Y) for detector loss into a thermal bath, frequency-aware.

    ``vacuum.core.channels.loss_XY`` in the mode's dimensionless
    quadratures, conjugated by :func:`mode_scaling`.  With ``gaps=None``
    this *is* ``loss_XY``.  At eta -> 0 the mode is replaced by
    (nbar + 1/2) diag(1/Omega_d, Omega_d) — exactly
    ``thermal_state_cov([[Omega_d^2]], T)`` for the bath occupation
    nbar = 1/(e^{Omega_d/T} - 1).
    """
    N = int(N)
    m = _mode_list(N, modes)
    X, Y = loss_XY(N, m, eta, nbar)
    if gaps is None:
        return X, Y
    return scale_channel(X, Y, mode_scaling(N, m, gaps))


def dephasing_XY(N, modes, D, axis="isotropic", gaps=None):
    """(X, Y) for the Gaussian dephasing channel (module docstring, item 2).

    Parameters
    ----------
    N : int
        Total number of modes.
    modes : sequence of int
        Modes to dephase (the detector modes).
    D : float
        Integrated dephasing strength, D = Gamma_phi * tau >= 0, in the
        dimensionless quadratures (added variance per quadrature for
        ``axis='isotropic'``).
    axis : {'isotropic', 'p', 'x'}
        'isotropic' (default, phase-covariant): Y~ = D I_2 per mode — the
        chosen circuit-QED mapping.  'p' / 'x': single-quadrature diffusion
        normalized to the same total added variance, Y~ = 2 D e_p e_p^T
        (resp. e_x e_x^T) — the spec's "thermal_noise on p only" variant.
    gaps : float, sequence or None
        Detector frequencies for the rescaling (None: dimensionless modes).

    Notes
    -----
    X = I always, so the Holevo-Werner condition reduces to Y >= 0, i.e.
    the channel is CP for every D >= 0 and every axis.
    """
    N = int(N)
    m = _mode_list(N, modes)
    D = float(D)
    if D < 0.0:
        raise ValueError(f"dephasing strength D must be >= 0, got {D}")
    if axis not in DEPHASING_AXES:
        raise ValueError(f"axis must be one of {DEPHASING_AXES}, got {axis!r}")
    if axis == "isotropic":
        X, Y = thermal_noise_XY(N, m, D)
    else:
        X = np.eye(2 * N)
        Y = np.zeros((2 * N, 2 * N))
        off = 0 if axis == "x" else N
        for k in m:
            Y[off + k, off + k] = 2.0 * D
    if gaps is None:
        return X, Y
    return scale_channel(X, Y, mode_scaling(N, m, gaps))


def dephasing(V, modes, D, axis="isotropic", gaps=None):
    """Apply the Gaussian dephasing channel to `modes` of V (pure function)."""
    V = np.asarray(V, dtype=float)
    N = V.shape[0] // 2
    X, Y = dephasing_XY(N, modes, D, axis=axis, gaps=gaps)
    return apply_channel(V, X, Y)


def detector_loss(V, modes, eta, nbar=0.0, gaps=None):
    """Apply frequency-aware loss to `modes` of V (pure function)."""
    V = np.asarray(V, dtype=float)
    N = V.shape[0] // 2
    X, Y = loss_channel_XY(N, modes, eta, nbar, gaps=gaps)
    return apply_channel(V, X, Y)


def imperfection_XY(N, modes, eta=1.0, nbar=0.0, dephasing=0.0, axis="isotropic",
                    gaps=None):
    """(X, Y) of the composed imperfection map: loss first, then dephasing.

    Composition of Gaussian channels (X2, Y2) o (X1, Y1) is
    (X2 X1, X2 Y1 X2^T + Y2); here X2 = I (dephasing is additive noise), so

        X = sqrt(eta) on the listed modes,   Y = Y_loss + Y_dephasing,

    both written in the original quadratures via :func:`mode_scaling`.
    The two pieces do NOT commute in general — dephasing first would give
    Y = eta Y_dephasing + Y_loss, a difference of order (1 - eta) D — and
    this module fixes the order as *loss then dephasing* (the noise added
    after the lossy interaction window is not attenuated by it).
    """
    N = int(N)
    m = _mode_list(N, modes)
    Xl, Yl = loss_channel_XY(N, m, eta, nbar, gaps=gaps)
    Xd, Yd = dephasing_XY(N, m, dephasing, axis=axis, gaps=gaps)
    return Xd @ Xl, Xd @ Yl @ Xd.T + Yd


def with_imperfections(V, modes, eta=1.0, nbar=0.0, dephasing=0.0,
                       axis="isotropic", gaps=None):
    """Compose detector loss and dephasing on `modes` of V (spec M2.6).

    The spec's ``with_imperfections(V, eta, nbar, dephasing)`` plus the
    mandatory mode set (which modes are the detectors is protocol
    information, not state information) and the optional detector gaps that
    make the channels frequency-aware.

    Parameters
    ----------
    V : (2N, 2N) ndarray
        Covariance (never mutated).
    modes : sequence of int
        Detector mode indices, e.g. ``range(N_field, N_tot)``.
    eta : float in [0, 1]
        Transmissivity of the detector loss channel; eta = exp(-Gamma_1 tau)
        for an energy-relaxation rate Gamma_1 over a window tau.  eta = 1 is
        the identity.
    nbar : float >= 0
        Bath occupation of the loss environment (see :func:`bath_occupation`).
    dephasing : float >= 0
        Integrated dephasing D = Gamma_phi * tau.
    axis : {'isotropic', 'p', 'x'}
        Dephasing anisotropy (see :func:`dephasing_XY`).
    gaps : float, sequence or None
        Detector frequencies Omega_d.  None keeps the bare dimensionless
        ``vacuum.core.channels`` convention.

    Returns
    -------
    (2N, 2N) ndarray
        ``dephasing(loss(V))`` — identical to
        ``apply_channel(V, *imperfection_XY(...))`` to roundoff.
    """
    V = np.asarray(V, dtype=float)
    N = V.shape[0] // 2
    X, Y = imperfection_XY(
        N, modes, eta=eta, nbar=nbar, dephasing=dephasing, axis=axis, gaps=gaps
    )
    return apply_channel(V, X, Y)


@dataclass(frozen=True)
class Imperfections:
    """Frozen record of a detector's imperfection parameters.

    Carries exactly the arguments of :func:`with_imperfections` (minus the
    state), so a sweep row can store the noise model it ran under.
    ``provenance`` names the ``experiments/`` file the numbers came from
    when they were loaded rather than chosen.
    """

    eta: float = 1.0
    nbar: float = 0.0
    dephasing: float = 0.0
    axis: str = "isotropic"
    gaps: Optional[Tuple[float, ...]] = None
    tau: Optional[float] = None
    provenance: Optional[str] = None

    def apply(self, V, modes):
        """Apply this noise model to `modes` of V."""
        return with_imperfections(
            V,
            modes,
            eta=self.eta,
            nbar=self.nbar,
            dephasing=self.dephasing,
            axis=self.axis,
            gaps=self.gaps,
        )

    def XY(self, N, modes):
        """(X, Y) of this noise model on an N-mode system."""
        return imperfection_XY(
            N,
            modes,
            eta=self.eta,
            nbar=self.nbar,
            dephasing=self.dephasing,
            axis=self.axis,
            gaps=self.gaps,
        )

    def is_identity(self, tol=0.0):
        """True iff the map is the identity channel (no loss, no dephasing)."""
        return abs(self.eta - 1.0) <= tol and abs(self.dephasing) <= tol


