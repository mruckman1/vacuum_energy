def accelerated_sequence(yN, ks=(0.5, 1.0, 1.5)):
    """FFR Eq. (66)-(67): (L^{(k)} y)_N = (N+1)/k (y_{N+1} - y_N) + y_N, applied for
    each k in `ks` in turn; the result is labelled as in their Table III, i.e.
    the entry using y_N .. y_{N+3} carries the label N + 1 (their N = 21 is
    built from y_20 .. y_23 in this convention; values agree to 11 digits)."""
    seq = dict(yN)
    for k in ks:
        Ns = sorted(seq)
        seq = {N: (N + 1) / k * (seq[N + 1] - seq[N]) + seq[N] for N in Ns[:-1]}
    return {N + 1: v for N, v in seq.items()}


